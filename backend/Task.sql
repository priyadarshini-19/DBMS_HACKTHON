DROP DATABASE IF EXISTS task_mgmt;
CREATE DATABASE task_mgmt;
USE task_mgmt;
CREATE TABLE users(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL,email VARCHAR(120) UNIQUE NOT NULL,password CHAR(64) NOT NULL,role ENUM('manager','employee') NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE skills(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(60) UNIQUE NOT NULL);
CREATE TABLE user_skills(user_id INT,skill_id INT,level INT DEFAULT 1,target INT DEFAULT 5,PRIMARY KEY(user_id,skill_id),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE);
CREATE TABLE skill_logs(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT,skill_id INT,level INT,logged_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE);
CREATE TABLE projects(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(150) NOT NULL,description TEXT,status ENUM('Planning','Active','Completed') DEFAULT 'Planning',deadline DATE,manager_id INT,FOREIGN KEY(manager_id) REFERENCES users(id) ON DELETE SET NULL);
CREATE TABLE tasks(id INT AUTO_INCREMENT PRIMARY KEY,project_id INT NOT NULL,title VARCHAR(150) NOT NULL,description TEXT,priority ENUM('Low','Medium','High') DEFAULT 'Medium',deadline DATE,status ENUM('To Do','In Progress','Done') DEFAULT 'To Do',progress INT DEFAULT 0,assigned_to INT NULL,FOREIGN KEY(project_id) REFERENCES projects(id) ON DELETE CASCADE,FOREIGN KEY(assigned_to) REFERENCES users(id) ON DELETE SET NULL);
CREATE TABLE task_skills(task_id INT,skill_id INT,PRIMARY KEY(task_id,skill_id),FOREIGN KEY(task_id) REFERENCES tasks(id) ON DELETE CASCADE,FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE);
CREATE TABLE planner(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,title VARCHAR(200) NOT NULL,priority ENUM('Low','Medium','High') DEFAULT 'Medium',plan_date DATE,done BOOLEAN DEFAULT FALSE,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE bottlenecks(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,title VARCHAR(200) NOT NULL,description TEXT,skill_id INT NULL,status ENUM('Open','Resolved') DEFAULT 'Open',created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE SET NULL);
CREATE TABLE replies(id INT AUTO_INCREMENT PRIMARY KEY,bottleneck_id INT NOT NULL,user_id INT NOT NULL,message TEXT NOT NULL,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(bottleneck_id) REFERENCES bottlenecks(id) ON DELETE CASCADE,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE notifications(id INT AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,message VARCHAR(300) NOT NULL,is_read BOOLEAN DEFAULT FALSE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);

